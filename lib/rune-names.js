// 룬 한글 표기 정본. 화면에 룬 이름을 쓰는 모든 탭(룬 추천·룬 재고·큐브·시세·신규 아이템·룬워드)이 여기만 본다.
//
// ⚠ 표시 전용이다. 저장·조회·검색 키는 영문 그대로 둔다 — localStorage 'runes:v1'의 키,
//    Redis 시세 제보의 unit(price.js UNIT_SET 검증), item-search 색인이 전부 영문에 묶여 있다.
//    여기서 한글을 데이터에 섞으면 기존 사용자 재고·제보가 조용히 깨진다.
//
// 표기 노선 = **통용명**(2026-07-29 사장님 확정). 게임 문자열 테이블(둔·아문·아이스트·조·샴)이 아니라
// 커뮤니티 통용 표기를 쓴다. 이미 farm-targets.js가 그 노선으로 확정·라이브 검증돼 있어 그쪽에 맞춘 것이다:
//   - 자(Jah)   2026-07-16 사장님 판정 (문자열 테이블 "조"는 alias로만)
//   - 이스트(Ist) 2026-07-16 사장님 판정 (문자열 테이블 "아이스트"는 alias로만)
//   - 말(Mal) · 참(Cham) 2026-07-18 사장님 확정
//   - 주울(Thul) · 에드(Eth) · 앰(Amn)  **2026-07-30 사장님 게임 클라이언트 실측 확정**
//   - 탈·오르트·랄·티르·솔·엘·돌  farm-targets.js:175 저급 룬 alias 목록
//   - 움(Um) · 조드(Zod)  app/cube/page.js 본문 · app/cube/layout.js 메타
// 나머지 12종(엘드·네프·이스·샤엘·헬·이오·룸·코·팔·렘·풀·굴)은 **사내 정본 출처가 없다** — 이견 없는 단순
// 음차라 그대로 넣었다. 게임 클라이언트와 다른 것이 확인되면 이 표만 고치면 전 탭이 따라온다.
//
// ⚠ 2026-07-30 교훈 — 이 표의 초판은 farm-targets.js:175 **alias 목록**을 표기 근거로 삼았는데
//   그중 3건(툴·엣·암)이 실제 게임 표기와 달랐다(→ 주울·에드·앰). alias는 "검색이 닿아야 하는 말"의
//   모음이지 표시 정본이 아니다 — 둘을 같은 것으로 취급한 게 오류였다.
//   **룬 한글 표기의 유일한 권위는 게임 클라이언트를 보유한 사장님이다**(mdb/overrides/ko-names.json 규약과 동일).
//   출처 없는 12종도 같은 이유로 언제든 틀릴 수 있다 — 확정 전까지 "검증됨"으로 취급하지 말 것.
export const RUNE_KR = {
  El: "엘", Eld: "엘드", Tir: "티르", Nef: "네프", Eth: "에드", Ith: "이스",
  Tal: "탈", Ral: "랄", Ort: "오르트", Thul: "주울", Amn: "앰", Sol: "솔",
  Shael: "샤엘", Dol: "돌", Hel: "헬", Io: "이오", Lum: "룸", Ko: "코",
  Fal: "팔", Lem: "렘", Pul: "풀", Um: "움", Mal: "말", Ist: "이스트",
  Gul: "굴", Vex: "벡스", Ohm: "옴", Lo: "로", Sur: "수르", Ber: "베르",
  Jah: "자", Cham: "참", Zod: "조드",
};

// 룬 하나의 표시 라벨. 한글(영문) 병기가 정본(2026-07-29 사장님 확정).
// 병기하는 이유는 두 가지다: ①거래·해외 가이드가 영문이라 대조가 필요하다
// ②이스(Ith)와 이스트(Ist)처럼 한글만으론 헷갈리는 쌍이 있다.
// 미지 룬은 영문 그대로 — 3.x 신규 룬워드의 runes 배열이 아직 미검증이라, 조용히 지우지 않고 눈에 보이게 둔다.
export function runeLabel(en) {
  const kr = RUNE_KR[en];
  return kr ? `${kr}(${en})` : en;
}

// 문장·데이터 문자열 안에 박힌 영문 룬 이름을 한글 표기로 바꾼다.
// 대상: lib/items.js의 meta("룬워드 · Hel + Shael + Ral · 3소켓 갑옷"), price-baseline의 std/ladder/note.
// 데이터 파일을 손대지 않고 표시 시점에만 바꾼다 — 그 파일들은 출처 주석이 붙은 정본이라 값을 흔들지 않는다.
// \b 경계라 Eld 가 El 로, Ist 가 Ith 로 잘리지 않는다(긴 이름 우선 정렬이 필요 없다).
const RUNE_TOKEN = new RegExp(`\\b(${Object.keys(RUNE_KR).join("|")})\\b`, "g");

// withEn=false 는 좁은 표 칸(시세 기준선의 "≈Ohm~Lo (5~14 Ist)")용이다 —
// 거기에 병기까지 넣으면 한 칸이 30자를 넘어 읽을 수 없다. 같은 화면의 룬 칩이 병기를 보여주므로 대조는 된다.
export function krRuneText(s, withEn = true) {
  return String(s ?? "").replace(RUNE_TOKEN, (m) => (withEn ? runeLabel(m) : RUNE_KR[m]));
}
